#!/usr/bin/env python3
"""Build dashboard/data/incidents.js from data/psfa_incidents.csv (stdlib only).

The output is a compact, columnar, dictionary-encoded structure assigned to
window.PSFA_DATA so the dashboard works over http:// and file:// alike.
All time binning is done here (in Pacific local time) - the browser never
re-bins timestamps in its own timezone.
"""
import csv
import json
import os
import sys
from datetime import date, datetime
from typing import Dict, List

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)

import derive  # noqa: E402

CSV_PATH = os.path.join(ROOT, "data", "psfa_incidents.csv")
OUT_PATH = os.path.join(ROOT, "dashboard", "data", "incidents.js")
FORMAT_VERSION = 1

csv.field_size_limit(10 ** 9)


class Dictionary:
    """Assigns stable integer codes to strings in first-seen order."""

    def __init__(self, seed: List[str] = None):
        self.values = []  # type: List[str]
        self.index = {}  # type: Dict[str, int]
        for v in seed or []:
            self.code(v)

    def code(self, value: str) -> int:
        if value not in self.index:
            self.index[value] = len(self.values)
            self.values.append(value)
        return self.index[value]


def build(rows: List[Dict[str, str]]) -> Dict:
    rows = [r for r in rows if r.get("status", "current") != "removed_upstream"]
    if not rows:
        raise SystemExit("No rows to build dashboard data from.")
    rows.sort(key=lambda r: r["call_local"])
    first_day = date.fromisoformat(rows[0]["date"])
    last_day = date.fromisoformat(rows[-1]["date"])
    win_start, win_end = derive.analysis_window(r["date"] for r in rows)

    cats = Dictionary(derive.CATEGORIES)
    types = Dictionary()
    type_info = []  # [label, level1, level2, level3, category_code]
    zips = Dictionary()
    aids = Dictionary(["None", "Given", "Received", "Both"])
    locs = Dictionary()
    acts = Dictionary()

    cols = {k: [] for k in ("d", "m", "c", "t", "u", "a", "z", "l", "ac", "lat", "lon", "id")}
    geo = {"ok": 0, "coarse": 0, "invalid": 0}
    for r in rows:
        d = (date.fromisoformat(r["date"]) - first_day).days
        cols["d"].append(d)
        cols["m"].append(int(r["minute_of_day"]))
        cat = cats.code(r["category"])
        cols["c"].append(cat)
        tkey = r["type_label"]
        if tkey not in types.index:
            type_info.append([tkey, r["type_level1"], r["type_level2"], r["type_level3"], cat])
        cols["t"].append(types.code(tkey))
        u = derive.to_int(r.get("units", ""))
        cols["u"].append(-1 if u is None else u)
        cols["a"].append(aids.code(r["aid"]))
        cols["z"].append(zips.code(r["zip"]))
        cols["l"].append(locs.code(r["location_use_group"]))
        paths = [p for p in r.get("actions", "").split("; ") if p]
        cols["ac"].append([acts.code(derive.action_label(p)) for p in paths])
        q = r.get("geo_quality", "invalid") or "invalid"
        geo[q] = geo.get(q, 0) + 1
        if q == "ok":
            cols["lat"].append(round(float(r["lat"]) * 1e5))
            cols["lon"].append(round(float(r["lon"]) * 1e5))
        else:
            cols["lat"].append(None)
            cols["lon"].append(None)
        cols["id"].append(r["cad_number"])

    meta = {
        "version": FORMAT_VERSION,
        "generated_at": datetime.now().strftime("%Y-%m-%d %H:%M"),
        "export_date": max(r.get("last_seen_export", "") for r in rows),
        "source": "NERIS Public - Incident Basics (USFA / FSRI)",
        "department": "Puget Sound Regional Fire Authority (%s)" % derive.PSFA_DEPT_ID,
        "rows": len(rows),
        "first_day": first_day.isoformat(),
        "last_day": last_day.isoformat(),
        "first_weekday": first_day.weekday(),  # 0 = Monday
        "window_start": win_start,
        "window_end": win_end,
        "shift_start_hour": derive.SHIFT_START_HOUR,
        "day_hours": [derive.DAY_START_HOUR, derive.DAY_END_HOUR],
        "geo": geo,
        "history_rows": sum(1 for r in rows if r.get("status") == "history"),
    }
    dicts = {
        "category": cats.values,
        "type": type_info,
        "zip": zips.values,
        "aid": aids.values,
        "loc": locs.values,
        "action": acts.values,
    }
    return {"meta": meta, "dict": dicts, "cols": cols}


def main() -> None:
    if not os.path.exists(CSV_PATH):
        raise SystemExit("Missing %s - run the update first." % CSV_PATH)
    with open(CSV_PATH, newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    data = build(rows)
    os.makedirs(os.path.dirname(OUT_PATH), exist_ok=True)
    tmp = OUT_PATH + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write("/* Generated by pipeline/build_dashboard_data.py - do not edit. */\n")
        f.write("window.PSFA_DATA = ")
        json.dump(data, f, separators=(",", ":"))
        f.write(";\n")
    os.replace(tmp, OUT_PATH)
    m = data["meta"]
    print("[build] Wrote %s: %d incidents, %s to %s (analysis window %s to %s)."
          % (os.path.relpath(OUT_PATH, ROOT), m["rows"], m["first_day"], m["last_day"],
             m["window_start"], m["window_end"]), flush=True)


if __name__ == "__main__":
    main()
